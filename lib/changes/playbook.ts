import { stringify } from "yaml";
import type { Platform } from "../core/types";
import { OPENS_BLOCK } from "./config-diff";
import type { Change } from "./store";

/**
 * Turns a proposed or approved change into an Ansible playbook, so it can be reviewed in git or run by an existing
 * pipeline. Running it through Ansible does NOT carry Tiny Snitch's protections: no snapshot is taken, nothing is read
 * back and verified, and there is no computed rollback. The header of the file says so.
 */
const MODULE: Partial<Record<Platform, string>> = {
  ios: "cisco.ios.ios_config",
  nxos: "cisco.nxos.nxos_config",
  eos: "arista.eos.eos_config",
  junos: "junipernetworks.junos.junos_config",
};

const COLLECTION: Partial<Record<Platform, string>> = {
  ios: "cisco.ios", nxos: "cisco.nxos", eos: "arista.eos", junos: "junipernetworks.junos",
};

export type Group = { parents: string[]; lines: string[] };

/**
 * Splits a flat command list into the (parents, lines) groups the config modules take. `interface X` starts a group;
 * `address-family ...` nests under the group it follows; anything before the first header has no parents.
 */
export function groupByParent(commands: string[]): Group[] {
  const groups: Group[] = [];
  let cur: Group | null = null;
  for (const c of commands) {
    const line = c.trim();
    if (OPENS_BLOCK.test(line)) {
      if (cur && cur.lines.length === 0 && /^address-family\b/i.test(line)) cur.parents.push(line);
      else if (cur && /^address-family\b/i.test(line)) { cur = { parents: [...cur.parents.slice(0, 1), line], lines: [] }; groups.push(cur); }
      else { cur = { parents: [line], lines: [] }; groups.push(cur); }
      continue;
    }
    if (!cur) { cur = { parents: [], lines: [] }; groups.push(cur); }
    cur.lines.push(line);
  }
  // A header with nothing under it (e.g. creating an empty interface) still has to be sent.
  return groups.map((g) => (g.lines.length === 0 && g.parents.length ? { parents: [], lines: g.parents } : g));
}

export class PlaybookError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "PlaybookError";
  }
}

/** Ansible reads `hosts:` as a pattern, where : , ! & * and spaces mean "these hosts and those". A plain name is required. */
const PLAIN_HOST = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
/** ...and `all` is the group of every host, so a device may not use it. */
const RESERVED = new Set(["all"]);

const safeName = (s: string) => s.replace(/[\r\n]+/g, " ").slice(0, 100);

export function renderPlaybook(change: Pick<Change, "id" | "title" | "intent" | "environment" | "plan" | "source">, generatedAt = new Date()): string {
  const high = change.plan.devices.flatMap((d) => d.risks.filter((r) => r.risk === "high").map((r) => `${d.label}: "${r.line}" (${r.reason})`));
  const header = [
    "# Generated by Tiny Snitch. Review every line before running it.",
    `# Change: ${safeName(change.title)}  (${change.environment}, ${change.source}, id ${change.id})`,
    ...(change.intent ? [`# Intent: ${safeName(change.intent)}`] : []),
    `# Generated: ${generatedAt.toISOString()}`,
    "#",
    "# Running this through Ansible does NOT carry Tiny Snitch's protections: no snapshot is taken, nothing is",
    "# read back and verified, and there is no computed rollback. Take your own backup first.",
    "# Hosts are the device names from your inventory; they must exist in the Ansible inventory you run it with.",
    ...(change.environment === "production" ? ["#", "# THIS CHANGE IS FOR A PRODUCTION NETWORK."] : []),
    ...(high.length ? ["#", "# High-risk lines in this change:", ...high.map((h) => `#   ${h.replace(/[\r\n]+/g, " ")}`)] : []),
    "",
  ].join("\n");

  for (const d of change.plan.devices) {
    if (!PLAIN_HOST.test(d.label) || RESERVED.has(d.label.toLowerCase())) throw new PlaybookError(`Device name "${d.label.slice(0, 40)}" has characters Ansible treats as a host pattern, so a play could target other hosts. Rename the device in your inventory (letters, digits, dot, dash, underscore) or apply this change in Tiny Snitch.`);
  }
  const plays = change.plan.devices.map((d) => {
    const module = MODULE[d.platform];
    if (!module) {
      return { name: `${d.label}: not supported (${d.platform})`, hosts: d.label, gather_facts: false, tasks: [{ name: `Tiny Snitch cannot render ${d.platform} devices; apply this change by hand`, "ansible.builtin.debug": { msg: d.commands } }] };
    }
    const tasks: Record<string, unknown>[] = [];
    if (d.platform === "junos") {
      // Junos takes set/delete lines as they are. A provisional commit is made, then confirmed in a second task.
      tasks.push({ name: `${d.label}: load and commit confirmed (10 minutes)`, [module]: { lines: d.commands, confirm: 10, comment: safeName(`Tiny Snitch: ${change.title}`) } });
      tasks.push({ name: `${d.label}: confirm the commit (skip this task to let the device revert)`, [module]: { confirm_commit: true } });
    } else {
      groupByParent(d.commands).forEach((g, i) => {
        tasks.push({
          name: g.parents.length ? `${d.label}: ${g.parents.join(" > ")}` : `${d.label}: configuration lines${i ? ` (part ${i + 1})` : ""}`,
          [module]: { ...(g.parents.length ? { parents: g.parents } : {}), lines: g.lines, save_when: "never" },
        });
      });
    }
    return { name: `${change.title}: ${d.label}`, hosts: d.label, gather_facts: false, collections: [COLLECTION[d.platform]], tasks };
  });
  return header + stringify(plays, { lineWidth: 0 });
}
